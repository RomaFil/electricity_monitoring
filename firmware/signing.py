# PlatformIO extra script (pre): signed firmware for remote updates (src/ota.cpp).
#
#   before the build: public.key -> $BUILD_DIR/signing/signing_key.h (built into the firmware)
#   after the build:  firmware.bin + RSA-2048 signature made with private.key -> firmware.bin.signed
#
# Keys: "python make_keys.py" once, on your own PC. public.key goes to git, private.key NEVER
# (it is git-ignored): whoever has it can flash the board from far away.
# Without public.key the firmware works as before: any image is accepted, remote updates are off.
#
# Signature format = what the ESP8266 core expects (Updater.cpp, tools/signing.py):
#   image | RSA PKCS#1 v1.5 SHA-256 signature (256 bytes) | signature length, uint32 little endian
import os
import shutil
import subprocess

Import("env")  # noqa: F821  (provided by PlatformIO)

PROJECT = env.subst("$PROJECT_DIR")  # noqa: F821
PUB = os.path.join(PROJECT, "public.key")
PRIV = os.path.join(PROJECT, "private.key")


def _openssl():
    found = shutil.which("openssl")
    if found:
        return found
    for p in (r"C:\Program Files\Git\usr\bin\openssl.exe", r"C:\Program Files\Git\mingw64\bin\openssl.exe"):
        if os.path.exists(p):
            return p
    return None


def public_from_private(priv_path):
    """PEM of the public half of private.key, to check that the two files belong together."""
    try:
        from cryptography.hazmat.primitives import serialization
        with open(priv_path, "rb") as f:
            key = serialization.load_pem_private_key(f.read(), password=None)
        return key.public_key().public_bytes(serialization.Encoding.PEM,
                                             serialization.PublicFormat.SubjectPublicKeyInfo).decode()
    except ImportError:
        tool = _openssl()
        if not tool:
            raise RuntimeError("need either 'pip install cryptography' or openssl (it comes with Git for Windows)")
        return subprocess.run([tool, "rsa", "-in", priv_path, "-pubout"], capture_output=True,
                              check=True).stdout.decode()


def sign(data, priv_path):
    try:
        from cryptography.hazmat.primitives import hashes, serialization
        from cryptography.hazmat.primitives.asymmetric import padding
        with open(priv_path, "rb") as f:
            key = serialization.load_pem_private_key(f.read(), password=None)
        sig = key.sign(data, padding.PKCS1v15(), hashes.SHA256())
    except ImportError:
        tool = _openssl()
        if not tool:
            raise RuntimeError("need either 'pip install cryptography' or openssl (it comes with Git for Windows)")
        sig = subprocess.run([tool, "dgst", "-sha256", "-sign", priv_path], input=data, capture_output=True,
                             check=True).stdout
    return data + sig + len(sig).to_bytes(4, "little")


def _pem(text):
    return "".join(text.split())  # compare keys regardless of line endings


# ---------- before the build: the public key as a C string ----------

pub_pem = ""
if os.path.exists(PUB):
    with open(PUB, encoding="ascii") as f:
        pub_pem = f.read().strip()
    if "BEGIN PUBLIC KEY" not in pub_pem:
        raise SystemExit("public.key is not a PEM public key (make it with: python make_keys.py)")

gen_dir = os.path.join(env.subst("$BUILD_DIR"), "signing")  # noqa: F821
os.makedirs(gen_dir, exist_ok=True)
header = ("#pragma once\n// Generated by signing.py from public.key. Do not edit.\n"
          f'static const char SIGNING_PUBKEY[] = R"KEY({pub_pem})KEY";\n')
header_path = os.path.join(gen_dir, "signing_key.h")
old = open(header_path, encoding="ascii").read() if os.path.exists(header_path) else None
if old != header:  # rewrite only on change, so the firmware is not rebuilt every time
    with open(header_path, "w", encoding="ascii") as f:
        f.write(header)
env.Append(CPPPATH=[gen_dir])  # noqa: F821
print("Firmware signing:", "ON (public.key)" if pub_pem else "off (no public.key: remote updates disabled)")


# ---------- after the build: firmware.bin.signed ----------

def sign_action(target, source, env):
    bin_path = str(target[0])
    out = bin_path + ".signed"
    if os.path.exists(out):
        os.remove(out)  # never leave an old signed image next to a new firmware.bin
    if not pub_pem:
        if os.path.exists(PRIV):
            print("WARNING: private.key exists but public.key does not; nothing is signed")
        return 0
    if not os.path.exists(PRIV):
        print("WARNING: this firmware accepts only signed images, but private.key is not here, "
              "so firmware.bin.signed was not made. Upload over USB or sign on the PC with the key.")
        return 0
    if _pem(public_from_private(PRIV)) != _pem(pub_pem):
        raise SystemExit("private.key does not match public.key: refusing to sign")
    with open(bin_path, "rb") as f:
        data = f.read()
    with open(out, "wb") as f:
        f.write(sign(data, PRIV))
    print(f"Signed: {out} ({len(data)} + 260 bytes)")
    return 0


env.AddPostAction("$BUILD_DIR/${PROGNAME}.bin", sign_action)  # noqa: F821
